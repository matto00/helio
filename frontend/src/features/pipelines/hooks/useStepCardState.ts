// useStepCardState — local editor state + persistence helpers for one
// pipeline-step row inside StepCard.
//
// Extracted from StepCard.tsx purely as a structural decomposition: the
// hook owns the per-op-kind editor states, keeps them in sync with the
// persisted `step.config` via the during-render `prev*` pattern, and
// exposes a single `persist` plus 26 typed change handlers that update
// local state and PATCH in lockstep. StepCard.tsx becomes a presentational
// shell over this hook.

import type { PipelineStepConfig } from "../types/pipelineStep";
import type { Step } from "../types/step";
import type { StepCardStateHandlers } from "./stepCardStateTypes";
import { useStepCardEditorState } from "./useStepCardEditorState";
import { buildStepCardFieldHandlers } from "./stepCardFieldHandlers";
import { buildStepCardOpHandlers } from "./stepCardOpHandlers";
import { useStepCardPersist } from "./useStepCardPersist";

export type { StepCardStateHandlers } from "./stepCardStateTypes";

export function useStepCardState(
  step: Step,
  /** Called for every edit; on the pipeline page it writes the edit into the client-only draft (HEL-1631). */
  onConfigChange: (stepId: string, config: PipelineStepConfig) => void,
): StepCardStateHandlers {
  const {
    selectedFields,
    setSelectedFields,
    renames,
    setRenames,
    casts,
    setCasts,
    filterConfig,
    setFilterConfig,
    computeConfig,
    setComputeConfig,
    aggregateConfig,
    setAggregateConfig,
    limitCount,
    setLimitCount,
    sortConfig,
    setSortConfig,
    splitTextConfig,
    setSplitTextConfig,
    extractHeadingsConfig,
    setExtractHeadingsConfig,
    chunkByTokenCountConfig,
    setChunkByTokenCountConfig,
    dateBucketConfig,
    setDateBucketConfig,
    pivotConfig,
    setPivotConfig,
    windowConfig,
    setWindowConfig,
    unpivotConfig,
    setUnpivotConfig,
    dedupeConfig,
    setDedupeConfig,
    fillNullConfig,
    setFillNullConfig,
    stringOpsConfig,
    setStringOpsConfig,
    unionConfig,
    setUnionConfig,
    lookupConfig,
    setLookupConfig,
    joinConfig,
    setJoinConfig,
    assertConfig,
    setAssertConfig,
    upsertSourceConfig,
    setUpsertSourceConfig,
    convertFormatConfig,
    setConvertFormatConfig,
    analyzeWithAiConfig,
    setAnalyzeWithAiConfig,
    generateTextConfig,
    setGenerateTextConfig,
    saveError,
    saveErrorIsValidation,
  } = useStepCardEditorState(step);
  const { persist, emitOrPersist } = useStepCardPersist({ step, onConfigChange });
  const {
    onFieldToggle,
    onRenameChange,
    onCastChange,
    onFilterChange,
    onComputeChange,
    onAggregateChange,
    onLimitChange,
    onSortChange,
    onSplitTextChange,
    onExtractHeadingsChange,
    onChunkByTokenCountChange,
    onDateBucketChange,
    onPivotChange,
    onWindowChange,
  } = buildStepCardFieldHandlers({
    selectedFields,
    setSelectedFields,
    renames,
    setRenames,
    casts,
    setCasts,
    setFilterConfig,
    setComputeConfig,
    setAggregateConfig,
    setLimitCount,
    setSortConfig,
    setSplitTextConfig,
    setExtractHeadingsConfig,
    setChunkByTokenCountConfig,
    setDateBucketConfig,
    setPivotConfig,
    setWindowConfig,
    persist,
  });
  const {
    onUnpivotChange,
    onDedupeChange,
    onFillNullChange,
    onStringOpsChange,
    onUnionChange,
    onLookupChange,
    onJoinChange,
    onAssertChange,
    onUpsertSourceChange,
    onConvertFormatChange,
    onAnalyzeWithAiChange,
    onGenerateTextChange,
  } = buildStepCardOpHandlers({
    setUnpivotConfig,
    setDedupeConfig,
    setFillNullConfig,
    setStringOpsConfig,
    setUnionConfig,
    setLookupConfig,
    setJoinConfig,
    setAssertConfig,
    setUpsertSourceConfig,
    setConvertFormatConfig,
    setAnalyzeWithAiConfig,
    setGenerateTextConfig,
    persist,
    emitOrPersist,
  });

  return {
    selectedFields,
    renames,
    casts,
    filterConfig,
    computeConfig,
    aggregateConfig,
    limitCount,
    sortConfig,
    splitTextConfig,
    extractHeadingsConfig,
    chunkByTokenCountConfig,
    dateBucketConfig,
    pivotConfig,
    windowConfig,
    unpivotConfig,
    dedupeConfig,
    fillNullConfig,
    stringOpsConfig,
    unionConfig,
    lookupConfig,
    joinConfig,
    assertConfig,
    upsertSourceConfig,
    convertFormatConfig,
    analyzeWithAiConfig,
    generateTextConfig,
    saveError,
    saveErrorIsValidation,
    onFieldToggle,
    onRenameChange,
    onCastChange,
    onFilterChange,
    onComputeChange,
    onAggregateChange,
    onLimitChange,
    onSortChange,
    onSplitTextChange,
    onExtractHeadingsChange,
    onChunkByTokenCountChange,
    onDateBucketChange,
    onPivotChange,
    onWindowChange,
    onUnpivotChange,
    onDedupeChange,
    onFillNullChange,
    onStringOpsChange,
    onUnionChange,
    onLookupChange,
    onJoinChange,
    onAssertChange,
    onUpsertSourceChange,
    onConvertFormatChange,
    onAnalyzeWithAiChange,
    onGenerateTextChange,
  };
}
